// Verifies server-rendered SEO output of a running build. Usage: node scripts/verify-seo.cjs [baseUrl]
const base = (process.argv[2] || "http://127.0.0.1:3200").replace(/\/+$/, "");
const failures = [];
const check = (ok, label) => { console.log(`${ok ? "PASS" : "FAIL"}  ${label}`); if (!ok) failures.push(label); };
(async () => {
  const home = await (await fetch(base + "/")).text();
  check(/<html lang="ro"/.test(home), 'homepage <html lang="ro">');
  check(home.includes("<title>DiversiBebe | Rețete pentru bebeluși și diversificare</title>"), "homepage title");
  check(!/Create Next App|Generated by create next app/.test(home), "no create-next-app defaults");
  check(/<meta name="description" content="[^"]{80,170}"/.test(home), "meta description 80-170 chars");
  check(/<link rel="canonical" href="https:\/\/www\.diversibebe\.com\/?"/.test(home), "canonical www");
  check(/property="og:image" content="https:\/\/www\.diversibebe\.com\/og-diversibebe\.png"/.test(home), "og:image absolute");
  check(/name="twitter:card" content="summary_large_image"/.test(home), "twitter card");
  check(/rel="icon" href="\/favicon\.ico/.test(home) && /rel="apple-touch-icon"/.test(home), "favicon + apple icon");
  const ld = home.match(/<script type="application\/ld\+json">([^<]*)<\/script>/);
  let parsed = null; try { parsed = ld && JSON.parse(ld[1]); } catch {}
  check(Boolean(parsed && parsed["@graph"]?.some((n) => n["@type"] === "WebSite")), "JSON-LD WebSite parses");
  const robots = await (await fetch(base + "/robots.txt")).text();
  check(/Sitemap: https:\/\/www\.diversibebe\.com\/sitemap\.xml/.test(robots), "robots.txt sitemap");
  const sitemap = await fetch(base + "/sitemap.xml");
  const xml = await sitemap.text();
  check(sitemap.ok && xml.includes("<loc>https://www.diversibebe.com/</loc>") && !/dashboard|profil|jurnal|plan|retete/.test(xml), "sitemap public-only");
  for (const p of ["/dashboard", "/profil", "/plan", "/login", "/register", "/retete/x"]) {
    const r = await fetch(base + p, { redirect: "manual" });
    check(/noindex/.test(r.headers.get("x-robots-tag") || ""), `${p} X-Robots-Tag noindex`);
  }
  const fav = await fetch(base + "/favicon.ico");
  check(fav.ok && (await fav.arrayBuffer()).byteLength > 0, "favicon.ico served");
  console.log(failures.length ? `\n${failures.length} failure(s)` : "\nAll SEO checks passed");
  process.exit(failures.length ? 1 : 0);
})().catch((e) => { console.error(e.message); process.exit(1); });
